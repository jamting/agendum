r"""Capture Lotus Agenda 2.0's F10 menus from the real program (DOSBox).

Walks the menus of a view, a note and the category manager, level by level,
and writes every entry's label and the help line Agenda shows when it is
highlighted to a JSON reference (default docs/reference/agenda_menus.json),
which Agendum's menu test compares with Agendum.TUI.Menu.tree/0 (meeting
2026-10-21-2324, § 8). Run by hand, never by the tests:

    AGENDA_DOS_ROOT=<scratch copy holding APPS/AGENDA> \
        python3 -u tools/agformat/capture_menus.py [FILE.AG] [out.json]

FILE.AG (default: PLANNER.AG of the copy) is copied to MC.AG and opened.
Afterwards (or alone, without DOSBox) the readable lists in
docs/reference/AGENDA_MENUS.md are written from the JSON:

    python3 tools/agformat/capture_menus.py --markdown

Safe walking (DRIVING_AGENDA.md, "Menus"): a highlighted entry's help is a
comma-separated list of names when it opens a submenu, and a sentence when
it runs a command. An entry is entered (by its letter) only when its help is
such a list; a command's help is read by moving onto it with RIGHT, so no
command ever runs. Every path starts afresh from the view (home()), and each
screen is checked, since keys are occasionally lost.
"""
import json, os, re, sys, time
import agenda_driver as d

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "docs", "reference", "agenda_menus.json")
MARKDOWN = os.path.join(HERE, "..", "..", "docs", "reference", "AGENDA_MENUS.md")

# how to reach each place's menu from the view, before F10
PLACES = {
    "view": [],
    # the note of the highlighted row (a category's note on a section head)
    "note": ["F5"],
    "catmgr": ["F9"],
}

SUBMENU = re.compile(r"[A-Z][\w/-]*(, [A-Z][\w/-]*)*")


def labels():
    """The entries on the menu's first line, as Agenda separates them."""
    return [w for w in re.split(r" {2,}", d.screen()[0].strip()) if w]


def reach(place, path, right=0, tries=4):
    """From the view: the place, F10, the letters of `path`, then RIGHT."""
    for _ in range(tries):
        d.home()
        for k in PLACES[place]:
            d.keys(k)
            d.idle()
        d.keys("F10")
        d.idle()
        ok = True
        for letter, expect in path:
            if not labels():
                ok = False
                break
            d.keys(letter)
            d.idle()
            # the level entered: its first entry is the one expected
            if labels()[:1] != [expect]:
                ok = False
                break
        if not ok:
            continue
        for _ in range(right):
            d.keys("RIGHT")
            d.idle()
        return True
    d.show()
    raise RuntimeError(f"cannot reach {place} {path}")


def walk(place, path=()):
    """The level at `path`: [{label, help, children?}], children walked too."""
    reach(place, path)
    names = labels()
    level = []
    for i, label in enumerate(names):
        reach(place, path, right=i)
        help_line = d.screen()[1].strip()
        entry = {"label": label, "help": help_line}
        if SUBMENU.fullmatch(help_line):
            # the help names the submenu's entries, its first one first
            first = help_line.split(", ")[0]
            entry["children"] = walk(place, path + ((label[0].lower(), first),))
        print("  " * len(path) + f"{label}: {help_line}", flush=True)
        level.append(entry)
    return level


# --- the readable lists -------------------------------------------------------

TITLES = {
    "view": "The view's menu (F10 in a view)",
    "note": "The note editor's menu (F10 in a note)",
    "catmgr": "The category manager's menu (F10 in the category manager)",
}
BEGIN = "<!-- generated by capture_menus.py --markdown: do not edit by hand -->"
END = "<!-- end of generated -->"


def lines(level, depth=0):
    for entry in level:
        if "children" in entry:
            yield "  " * depth + f"- **{entry['label']}**"
            yield from lines(entry["children"], depth + 1)
        else:
            yield "  " * depth + f"- **{entry['label']}**: {entry['help']}"


def markdown(json_path=OUT, md_path=MARKDOWN):
    """Rewrites the generated part of AGENDA_MENUS.md from the JSON."""
    reference = json.load(open(json_path))
    parts = [BEGIN, ""]
    for place, level in reference["menus"].items():
        parts += [f"## {TITLES[place]}", "", "`" + " · ".join(e["label"] for e in level) + "`", ""]
        parts += list(lines(level)) + [""]
    parts.append(END)
    text = open(md_path).read()
    start, stop = text.index(BEGIN), text.index(END) + len(END)
    with open(md_path, "w") as f:
        f.write(text[:start] + "\n".join(parts) + text[stop:])
    print(f"written {md_path}")


def main():
    if sys.argv[1:] == ["--markdown"]:
        return markdown()
    base = sys.argv[1] if len(sys.argv) > 1 else os.path.join(d.AG, "PLANNER.AG")
    out = sys.argv[2] if len(sys.argv) > 2 else OUT
    d.fresh("MC", base)
    d.idle()
    try:
        menus = {}
        for place in PLACES:
            print(f"# {place}", flush=True)
            menus[place] = walk(place)
        d.home()
    finally:
        # leave without saving: Abandon is never chosen, so quit by killing
        d.proc.kill()
        d.proc.wait()

    reference = {
        "source": "Lotus Agenda 2.0 in DOSBox Staging, tools/agformat/capture_menus.py",
        "captured": time.strftime("%Y-%m-%d"),
        "menus": menus,
    }
    with open(out, "w") as f:
        json.dump(reference, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"written {out}")
    if out == OUT:
        markdown()


if __name__ == "__main__":
    main()
